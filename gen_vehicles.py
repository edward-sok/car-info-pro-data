def T(name, msrp, pt, engine, hp, tq, trans, drive, city=None, hwy=None, comb=None, zero=None,
      mpge=None, rng=None, batt=None, zero100=None):
    """Trim in US units (hp, lb-ft, mpg, miles, 0-60 mph). msrp is in the market's currency."""
    return dict(name=name, msrp=msrp, powertrain=pt, engine=engine, horsepower=hp, torque=tq,
                transmission=trans, drivetrain=drive, mpgCity=city, mpgHighway=hwy, mpgCombined=comb,
                mpge=mpge, electricRange=rng, batteryKWh=batt, zeroToSixty=zero, zeroTo100=zero100)


def TM(name, price, pt, engine, kw, nm, trans, drive, l100=None, zero100=None, rng_km=None,
       batt=None, kml=None):
    """Trim from metric figures (kW, Nm, L/100km or km/L, km, 0-100 km/h); stored in US units."""
    if kml:
        l100 = 100 / kml
    return T(name, price, pt, engine, round(kw / 0.7457), round(nm / 1.3558) if nm else None, trans, drive,
             comb=round(235.215 / l100) if l100 else None, rng=round(rng_km / 1.6093) if rng_km else None,
             batt=batt, zero100=zero100)

def D(length, width, height, wb, gc, weight, seats, cargo, cargo_max=None, fuel=None, tow=None,
      payload=None, bed=None):
    return dict(length=length, width=width, height=height, wheelbase=wb, groundClearance=gc,
                curbWeight=weight, seating=seats, cargo=cargo, cargoMax=cargo_max, fuelCapacity=fuel,
                towing=tow, payload=payload, bedLength=bed)

def DM(length, width, height, wb, gc, kg, seats, cargo_l=None, cargo_max_l=None, fuel_l=None,
       tow_kg=None, payload_kg=None, bed_mm=None):
    """Dimensions from metric figures (mm, kg, litres); stored in US units."""
    inch = lambda mm: round(mm / 25.4, 1) if mm else None
    cuft = lambda l: round(l / 28.3168, 1) if l else None
    lb = lambda k: round(k * 2.20462) if k else None
    return D(inch(length), inch(width), inch(height), inch(wb), inch(gc), lb(kg), seats, cuft(cargo_l),
             cuft(cargo_max_l), round(fuel_l / 3.78541, 1) if fuel_l else None, lb(tow_kg), lb(payload_kg),
             inch(bed_mm))


